drop policy if exists profiles_self_read on public.profiles;
create policy profiles_self_read on public.profiles for select
  using (id = auth.uid() or public.is_staff());
drop policy if exists profiles_self_update on public.profiles;
create policy profiles_self_update on public.profiles for update
  using (id = auth.uid()) with check (id = auth.uid() and role = (select role from public.profiles p where p.id = auth.uid()));

drop policy if exists invites_staff on public.invites;
create policy invites_staff on public.invites for all
  using (public.is_staff()) with check (public.is_staff());

drop policy if exists orgs_read on public.orgs;
create policy orgs_read on public.orgs for select using (auth.role() = 'authenticated');
drop policy if exists orgs_write on public.orgs;
create policy orgs_write on public.orgs for insert with check (public.is_staff());
drop policy if exists orgs_update on public.orgs;
create policy orgs_update on public.orgs for update using (public.is_staff()) with check (public.is_staff());
drop policy if exists orgs_delete on public.orgs;
create policy orgs_delete on public.orgs for delete using (public.is_staff());

drop policy if exists versions_staff_read on public.org_versions;
create policy versions_staff_read on public.org_versions for select using (public.is_staff());

drop policy if exists donations_own on public.donations;
create policy donations_own on public.donations for all
  using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists donations_staff_read on public.donations;
create policy donations_staff_read on public.donations for select using (public.is_staff());

drop policy if exists shortlist_own on public.shortlist;
create policy shortlist_own on public.shortlist for all
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists comments_staff on public.org_comments;
create policy comments_staff on public.org_comments for all
  using (public.is_staff()) with check (public.is_staff());

drop policy if exists cell_notes_staff on public.org_cell_notes;
create policy cell_notes_staff on public.org_cell_notes for all
  using (public.is_staff()) with check (public.is_staff());

